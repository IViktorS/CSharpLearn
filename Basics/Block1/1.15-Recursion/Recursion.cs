    private static int MaxDepth(Node node)
    {
        if ( node == null )
            return 0;

        if( node.Children.Count == 0 )
            return 1;

        var maxDepth = 0;
        foreach (var child in node.Children)
        {
            var currentDepth = MaxDepth(child);
            maxDepth = maxDepth >= currentDepth ? maxDepth : currentDepth;
        }

        return maxDepth + 1;
    }

    private static int SumValue(Node node)
    {
        var sum = 0;

        // Базовый случай: если у узла нет детей, возвращаем его Value.
        if (node.Children.Count == 0)
            return node.Value;

        foreach (var child in node.Children)
            sum += SumValue(child);

        return sum + node.Value;
    }

