    private static int calls;

    private static int Fib(int n)
    {
        calls++;
        if (n <= 1) return n;
        return Fib(n - 1) + Fib(n - 2);
    }

    private static int FibFast(int n)
    {
        int prev = 0; 
        int curr = 1; 

        if (n == 0)
        {
            curr = 0;
        }
        else
        {
            for (int i = 2; i <= n; i++)
            {
                int next = prev + curr; 
                prev = curr;            
                curr = next;            
            }
        }

        return curr;
    }

