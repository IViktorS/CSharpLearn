namespace Basics.Block1;

// 1.14 Pattern matching — задачи
//
// Правила прежние: сначала заполняешь ПРЕДСКАЗАНИЕ, потом запускаешь.
// Строки, помеченные «раскомментируй», — сначала предскажи код ошибки,
// потом проверь. По умолчанию после этого комментарий возвращается на место;
// где вместо этого нужно ПОЧИНИТЬ код — сказано прямо в самой строке.
//
// Запуск:  dotnet run --project Basics -- 1.14

public static class PatternMatching
{
    public static void Run()
    {
        Task1();
        Task2();
        Task3();
        Task4();
    }

    private enum Status { Draft, Active, Closed }

    // ── ЗАДАЧА 1: switch-выражение, порядок и полнота ─────────────────────
    // Метод Label ниже НЕ имеет ветки `_`.
    //
    // ПРЕДСКАЗАНИЕ (1) какой warning выдаст компилятор на Label
    //                  (код и в чём претензия): CS8524 не может обработать все варианты входящего значения Status. Если вдруг в переменной окажется значение, которое не соответствует ни одной из веток switch, то будет исключение.
    // ПРЕДСКАЗАНИЕ (2) Label(Status.Active): активен
    // ПРЕДСКАЗАНИЕ (3) что произойдёт при вызове Label((Status)99)
    //                  и почему такое значение вообще может оказаться
    //                  в переменной типа Status: Будет SwitchExpressionException. Такое значение может оказаться по тому, что под капотом Enum хранит int. И ничто не мешает попытаться скастить сисло к данному перечислению.
    // ПРЕДСКАЗАНИЕ (4) код ошибки для метода Broken (строка А): CS8510
    //
    // ЗАДАНИЕ: после того как всё предскажешь и проверишь — почини Label
    // так, чтобы warning исчез, а (Status)99 не ронял программу.
    private static void Task1()
    {
        Console.WriteLine("--- Задача 1 ---");

        Console.WriteLine($"Label(Active) = {Label(Status.Active)}");

        // Строка Б — раскомментируй, посмотри, ВРЕМЕННО верни комментарий:
        // без него программа падает здесь же и до задач 2 и 3 не доходит.
        // После того как починишь Label — раскомментируй НАСОВСЕМ:
        // эта строка и есть проверка, что починка работает.
        Console.WriteLine($"Label((Status)99) = {Label((Status)99)}");
    }

    private static string Label(Status s) => s switch
    {
        Status.Draft => "черновик",
        Status.Active => "активен",
        Status.Closed => "закрыт",
        _ => "неизвестно",
    };

    // Строка А — раскомментируй метод целиком, посмотри ошибку. Дальше не
    // возвращай комментарий, а ПОЧИНИ порядок ветвей и оставь метод рабочим
    // (вызывать его из Task1 не обязательно — достаточно, чтобы собирался):
    private static string Broken(int n) => n switch
    {
        > 0 => "положительное",
        _ => "любое",
    };

    // ── ЗАДАЧА 2: is-паттерны и точность типа ─────────────────────────────
    // Здесь важно не только «что вернёт», но и ПОЧЕМУ — по какому типу
    // принимается решение: по типу объекта в куче (проверка в рантайме)
    // или по объявленному типу переменной (решает компилятор).
    //
    // Формат ответа: в пунктах (1)–(5) рядом со значением припиши механизм
    // в 3–5 слов, например «false — в коробке int, проверка на точное
    // совпадение». В пункте (6) нужно развёрнуто: там ошибка компиляции,
    // и объяснить надо ПОЧЕМУ компилятор не может принять строку,
    // а не пересказать текст ошибки.
    //
    // ПРЕДСКАЗАНИЕ (1) a is long: false в коробке int - проверка на точное совпадение.
    // ПРЕДСКАЗАНИЕ (2) b is long: true в коробке long - проверка на точное совпадение.
    // ПРЕДСКАЗАНИЕ (3) a is int and > 3: true в коробке int и значение > 3. Проверяются последовательно оба условия.
    // ПРЕДСКАЗАНИЕ (4) c is null / c is int: true в переменной  null - проверка на точное совпадение. / false в переменной null - проверка на точное совпадение.
    // ПРЕДСКАЗАНИЕ (5) что выведет ветка с d (и что окажется в str): ветка выведет HELLO, а в str окажется hello. Сперва идет проверка, что в переменной именно string, если да, то проверяется, что свойство Length > 3.
    // ToUpper возвращает копию строки в верхнем регистре.
    // ПРЕДСКАЗАНИЕ (6) код ошибки на строке В и объяснение, почему
    //                  компилятор вообще не может это скомпилировать: CS0117 не мо жет скомпилировать, так как мы пытаемся обратиться сразу к свойству Length, но непонятно у какого типа, так как он не проверяется. 
    private static void Task2()
    {
        Console.WriteLine("--- Задача 2 ---");

        object a = 5;
        object b = 5L;
        int? c = null;
        object d = "hello";

        Console.WriteLine($"a is long        : {a is long}");
        Console.WriteLine($"b is long        : {b is long}");
        Console.WriteLine($"a is int and > 3 : {a is int and > 3}");
        Console.WriteLine($"c is null        : {c is null}");
        Console.WriteLine($"c is int         : {c is int}");

        if (d is string { Length: > 3 } str)
            Console.WriteLine($"длинная строка   : {str.ToUpper()}");
        else
            Console.WriteLine("не подошло");

        // Строка В — раскомментируй, посмотри ошибку. Потом верни комментарий
        // и НИЖЕ напиши рабочий вариант той же проверки («у d длина 5»),
        // изменив паттерн так, чтобы компилятор его принял:
        // Console.WriteLine($"d is {{ Length: 5 }} : {d is { Length: 5 }}");

        Console.WriteLine($"d is {{ Length: 5 }} : {d is string { Length: 5 }}");
    }

    // Мини-справка к задаче 3: тип может ПЕРЕГРУЗИТЬ операторы == и != —
    // объявить собственный метод `public static bool operator ==(...)`,
    // который вызывается вместо стандартного сравнения. Именно так устроен
    // string (поэтому `==` на строках сравнивает содержимое). Подробно
    // перегрузка операторов и правильное переопределение равенства — тема 2.6;
    // здесь достаточно знать, что такой метод бывает и его пишет автор типа.
    //
    // `#pragma warning disable` глушит предупреждение о том, что вместе с ==
    // положено переопределять ещё пару методов, — это тоже тема 2.6.
    //
    // Как это читать. `public static bool operator ==(...)` — обычный
    // статический метод со специальным именем. Увидев `x == y`, где
    // ОБЪЯВЛЕННЫЙ тип операндов — Doc, компилятор превращает строку в вызов
    // этого метода; `null` тоже приводится к `Doc?`, так что `doc != null` —
    // это вызов, а не встроенное сравнение ссылок.
    //
    // Почему внутри стоит ReferenceEquals(left, null), а не left == null:
    // `left == null` — это снова ЭТОТ ЖЕ оператор, то есть бесконечная
    // рекурсия и StackOverflow. ReferenceEquals перегрузить нельзя, он всегда
    // спрашивает «это одна и та же ссылка» — потому внутри такого метода он
    // единственный надёжный способ проверить настоящий null. Тем же свойством
    // «меня нельзя перегрузить» держится и `is not null`.
    //
    // Что требуется от тебя: НЕ писать такие операторы (это 2.6), а пройти
    // по телу вручную — какая ветвь сработает для Value == 0 против null,
    // и что после этого вернёт `!=`, который определён как !(left == right).
    //
    // Это не выдуманная экзотика: в Unity UnityEngine.Object перегружает ==
    // так же, и у уничтоженного объекта `obj != null` даёт false при живой
    // ссылке — на этом регулярно спотыкаются.

#pragma warning disable 660, 661
    private class Doc
    {
        public int Value;

        // Автор типа решил: документ с Value == 0 — это «пустой документ»,
        // и он должен считаться равным null.
        public static bool operator ==(Doc? left, Doc? right)
        {
            if (ReferenceEquals(left, null))
                return ReferenceEquals(right, null) || right!.Value == 0;
            if (ReferenceEquals(right, null))
                return left.Value == 0;
            return left.Value == right.Value;
        }

        public static bool operator !=(Doc? left, Doc? right) => !(left == right);
    }
#pragma warning restore 660, 661

    // ── ЗАДАЧА 3: != null против is not null ──────────────────────────────
    // Здесь «очевидный» ответ неверен как минимум в одной строке.
    // Объект `doc` создан через new — он совершенно точно существует.
    //
    // ПРЕДСКАЗАНИЕ (1) doc != null: false вызов перегруженного оператора ==, который проверяет Value == 0, и возвращает true, а затем оператор != инвертирует результат.
    // Мы попадаем в ветку if (ReferenceEquals(right, null)) и проверяем left.Value == 0, что верно, так как doc.Value == 0. Поэтому doc != null возвращает false.
    // (В этой ветви right и есть null, поэтому читать можно только left — обращение к right.Value бросило бы NullReferenceException.)
    // ПРЕДСКАЗАНИЕ (2) doc is not null: true так как тут мы делаем проверку напрямую, без перегрузки. Что важно, эта проверка более надежная, так как ее не подменишь перегрузкой.
    // ПРЕДСКАЗАНИЕ (3) od != null            (od — ТОТ ЖЕ объект, но object): true я понимаю это так. Поскольку это получается boxing, то проверка смотрит, что лежит в коробке, а в коробке лежит ссылка на экземпляр класса,
    // соответственно это != null.
    // ПОПРАВКА (после разбора): значение true верное, но boxing тут ни при чём — его вообще нет.
    // Doc это КЛАСС, ссылочный тип: `object od = doc;` копирует ссылку, коробка не создаётся
    // (boxing бывает только у значимых типов — 1.4/1.1). Настоящий механизм: объявленный тип
    // переменной od — object, у object оператор == не перегружен, поэтому компилятор берёт
    // обычное сравнение ссылок; ссылка не нулевая → true. Перегрузка Doc не вызывается,
    // потому что в этой строке компилятор про Doc не знает. См. задачу 4.
    // ПРЕДСКАЗАНИЕ (4) od is not null: true суть как и в предсказании 3
    // ПРЕДСКАЗАНИЕ (5) если (1) и (3) разошлись — что именно изменилось,
    //                  раз объект один и тот же? Объект один и тот же, но в 3 случае он в коробке и смотрим мы на него как на то, null там или нет, не доходя до перегрузки оператора.
    // ПОПРАВКА (после разбора): «не доходя до перегрузки оператора» — верно и это главное.
    // Неверно «он в коробке»: коробки нет, объект один и тот же и лежит там же. Изменился ТОЛЬКО
    // объявленный тип переменной, и по нему компилятор выбрал другой оператор == (стандартный
    // вместо перегрузки Doc). Тот же механизм, что на контрольной точке 1 в задаче 4:
    // оператор выбирается статически, по типу переменной, а не по типу объекта в куче.
    // ПРЕДСКАЗАНИЕ (6) код ошибки на строке Г: CS8780, CS0165 переменная должна быть обязательно присвоена. Сейчас возможен случай, когда od будет long, а в консоль мы попытаемся вывести несуществующую переменную.
    //
    // ЗАДАНИЕ: сформулируй в комментарии правило — когда `!= null` нельзя
    // доверять и почему `is not null` от этой проблемы свободен. is not null нельзя перегрузить, по этому это является надежной проверкой. Паттерну `!= null` нельзя доверять, так как он может быть перегружен и вести себя не так, как ожидается.
    // В случае перегрузки оператора `==`, проверка на null может возвращать неожиданные результаты, что делает её ненадежной в некоторых сценариях.
    private static void Task3()
    {
        Console.WriteLine("--- Задача 3 ---");

        var doc = new Doc { Value = 0 };
        object od = doc;

        Console.WriteLine($"doc != null      : {doc != null}");
        Console.WriteLine($"doc is not null  : {doc is not null}");
        Console.WriteLine($"od != null       : {od != null}");
        Console.WriteLine($"od is not null   : {od is not null}");

        // Строка Г — раскомментируй, посмотри ошибку, верни комментарий:
        // if (od is int n or long) Console.WriteLine(n);
    }

    // ── ЗАДАЧА 4: boxing бывает не у всех ─────────────────────────────────
    // Добавлена после проверки: в задаче 3 поведение `od != null` было
    // объяснено через boxing, которого там нет.
    //
    // Идея задачи: если присваивание `object x = ссылочный_тип` создавало бы
    // коробку, то ДВА таких присваивания одного и того же объекта дали бы
    // ДВЕ разные коробки — и ReferenceEquals увидел бы разные объекты.
    // Проверяем это напрямую и сравниваем со значимым типом.
    //
    // ПРЕДСКАЗАНИЕ (1) ReferenceEquals(v1, v2) — два раза упаковали int 42: false, так как каждый раз создается новая коробка в куче, соответственно и ссылки будут разные.
    // ПРЕДСКАЗАНИЕ (2) ReferenceEquals(r1, r2) — два раза присвоили ОДИН
    //                  объект класса в переменные типа object: true, тут нет боксинга. Мы просто присвоили одну ссылку двум переменным. По этому при сравнении они будут равны.
    // ПРЕДСКАЗАНИЕ (3) если (1) и (2) разошлись — почему? Что физически
    //                  происходит в куче в первом случае и во втором? Разошлись они по причине того, что в первом случае у нас значимые типы, которые хранятся в стеке. При боксинге они упаковываются и размещаются в куче, и на каждую коробку ведт своя ссылка.
    // Во втором случае у нас экземпляр класса, который и так хранится в куче и мы присваиваем в переменные одну и ту же ссылку на этот экземпляр.
    // ПРЕДСКАЗАНИЕ (4) ReferenceEquals(s1, s2) — два раза присвоили ОДНУ
    //                  структуру в переменные типа object: false, так как структура является значимым типом и при присвоении в переменную типа object происходит боксминг, каждая переменная будет в своей коробке и со своей ссылкой.
    // ПРЕДСКАЗАНИЕ (5) какой из трёх случаев (1)/(2)/(4) — это boxing,
    //                  а какой нет, и по какому признаку ты это определяешь: 1 и 4 — это boxing, так как мы присваиваем значимые типы в переменные типа object. 2 — это не boxing, так как мы присваиваем ссылочный тип в переменную типа object.
    private static void Task4()
    {
        Console.WriteLine("--- Задача 4 ---");

        // Значимый тип: каждое присваивание в object — отдельная упаковка
        object v1 = 42;
        object v2 = 42;
        Console.WriteLine($"ReferenceEquals(v1, v2) : {ReferenceEquals(v1, v2)}");

        // Ссылочный тип: один объект, две переменные
        var doc = new Doc { Value = 7 };
        object r1 = doc;
        object r2 = doc;
        Console.WriteLine($"ReferenceEquals(r1, r2) : {ReferenceEquals(r1, r2)}");

        // Значимый тип, но своя структура — и ОДНА переменная-источник
        var counter = new Counter { Value = 7 };
        object s1 = counter;
        object s2 = counter;
        Console.WriteLine($"ReferenceEquals(s1, s2) : {ReferenceEquals(s1, s2)}");
    }

    private struct Counter
    {
        public int Value;
    }
}
