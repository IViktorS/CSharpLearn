/// <summary>Объект, который «считает сам себя». Задумка автора — общий счётчик созданных.</summary>
public class Tracked<T>
{
    /// <summary>Сколько объектов создано.</summary>
    public static int Created;

    /// <summary>Создаёт объект и увеличивает счётчик.</summary>
    public Tracked() => Created++;
}

