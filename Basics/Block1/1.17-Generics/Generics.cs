//Каких то других развилок не возникало.
public class MachineParameters<T>
{
    private T? _value;
    private bool _hasValue = false;

    public void SetValue(T value)
    {
        _value = value;
        _hasValue = true;
    }

    public T? GetValue() => !_hasValue ? default : _value!;

    public bool HasValue() => _hasValue;
}

