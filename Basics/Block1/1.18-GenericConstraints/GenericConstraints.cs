/// <summary>Два метода с противоположными ограничениями.</summary>
public static class Gate
{
    /// <summary>Принимает только значимые типы.</summary>
    public static string Val<T>(T x) where T : struct => $"Val: {typeof(T).Name}";

    /// <summary>Принимает только ссылочные типы.</summary>
    public static string Ref<T>(T x) where T : class => $"Ref: {typeof(T).Name}";
}

