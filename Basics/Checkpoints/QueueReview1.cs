            Console.WriteLine($"Найден элемент: {notFound}");
        }
        else
        {
            Console.WriteLine($"Элемент не найден: {notFound}");
        }

        if (TryGet(numbers, 0, out int element))
        {
            Console.WriteLine($"Найден элемент: {element}");
        }
        else
        {
            Console.WriteLine($"Элемент не найден: {element}");
        }

